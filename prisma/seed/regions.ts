const SIGUNGU_SUFFIX: Readonly<Record<string, string>> = { 구: "GU", 군: "GUN", 시: "SI" };

/** UPPER_SNAKE code for a 시·군·구, e.g. ("GYEONGBUK", "의성군") → "GYEONGBUK_UISEONG_GUN". */
export function sigunguCode(sido: string, name: string): string {
  const suffix = SIGUNGU_SUFFIX[name.slice(-1)];
  const roman = SIGUNGU_ROMAN[name.slice(0, -1)];
  if (!suffix || !roman) {
    throw new Error(
      `regions seed: no romanization for "${name}" (${sido}) — add it to SIGUNGU_ROMAN`,
    );
  }
  return `${sido}_${roman}_${suffix}`;
}

export async function seedRegions(prisma: PrismaClient): Promise<number> {
  let count = 0;
  for (const [i, s] of SIDO.entries()) {
    const unknown = s.depopulation.filter((d) => !s.sigungu.includes(d));
    if (unknown.length > 0) {
      throw new Error(
        `regions seed: ${s.code} depopulation not in sigungu list: ${unknown.join(", ")}`,
      );
    }
    const sidoData = {
      level: "SIDO" as const,
      nameKo: s.nameKo,
      nameKey: `common.region.${s.code.toLowerCase()}`,
      parentCode: null,
      depopulationArea: false,
      isSample: true,
      needsReview: true,
      sortOrder: i + 1,
    };
    await prisma.region.upsert({
      where: { code: s.code },
      create: { code: s.code, ...sidoData },
      update: {},
    });
    count++;
    for (const [j, name] of s.sigungu.entries()) {
      const code = sigunguCode(s.code, name);
      const data = {
        level: "SIGUNGU" as const,
        nameKo: name,
        nameKey: null,
        parentCode: s.code,
        depopulationArea: s.depopulation.includes(name),
        isSample: true,
        needsReview: true,
        sortOrder: j + 1,
      };
      await prisma.region.upsert({ where: { code }, create: { code, ...data }, update: {} });
      count++;
    }
  }
  return count;
}
